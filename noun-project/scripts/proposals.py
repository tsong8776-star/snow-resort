        if key in seen:
            note = (note + " / " if note else "") + f"제목 중복(#{seen[key]})"
        seen.setdefault(key, n)
        w.writerow([n, ic["id"], ic["title"], title, tags, s, note,
                    "https://thenounproject.com" + ic["url"]])
